/** Generates packages/dictionary/src/ichiran-build/errata-data.ts from Ichiran's
 * dict-errata.lisp (MIT). The add-errata function and the add-errata-* functions
 * it calls are flattened into an ordered list of data operations; nothing is
 * evaluated. Unknown forms abort generation.
 *
 *   node --import tsx scripts/ichiran-build/convert-errata.ts ../references/ichiran
 */
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { readLisp } from "../extract-ichiran-tests.js";

type Node = ReturnType<typeof readLisp>[number];
const repo = process.argv[2] ?? "../references/ichiran";
const path = join(repo, "dict-errata.lisp");
const source = await readFile(path, "utf8");
const commit = execFileSync("git", ["-C", repo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const forms = readLisp(source);
const defuns = new Map<string, Node[]>();
for (const f of forms)
  if (f.kind === "list" && f.children[0]?.value === "defun") defuns.set(f.children[1].value, f.children.slice(3));

const atom = (n: Node): unknown => {
  if (n.kind === "string") return n.value;
  if (n.kind === "symbol") {
    if (/^-?\d+$/.test(n.value)) return Number(n.value);
    if (n.value === ":null") return null;
    if (n.value === "t") return true;
    if (n.value === "nil") return false;
    if (n.value.startsWith(":")) return n.value.slice(1);
    throw new Error(`unexpected symbol ${n.value} at line ${n.line}`);
  }
  if (n.children[0]?.value === "quote") {
    const q = n.children[1];
    if (q.kind === "symbol") return q.value === "kana-text" ? "kana" : q.value === "kanji-text" ? "kanji" : q.value;
    return q.children.map(atom);
  }
  throw new Error(`unexpected form at line ${n.line}`);
};

const ops: unknown[][] = [];
const SIMPLE = new Set([
  "conjugate-da", "add-deha-ja-readings", "remove-hiragana-nokanji", "add-gozaimasu-conjs",
  "set-primary-nokanji", "add-primary-nokanji", "delete-reading", "add-reading", "set-common",
  "delete-sense-prop", "add-sense-prop", "add-new-sense*", "add-conj-reading", "rearrange-readings-conj",
  "delete-conjugation", "replace-reading", "replace-reading-conj", "add-gloss",
]);
function emit(body: Node[]) {
  for (const f of body) {
    if (f.kind !== "list") throw new Error(`unexpected atom at line ${f.line}`);
    const head = f.children[0].value;
    const args = f.children.slice(1);
    if (head.startsWith("add-errata-")) {
      const sub = defuns.get(head);
      if (!sub) throw new Error(`missing ${head}`);
      emit(sub);
    } else if (SIMPLE.has(head)) {
      const positional: unknown[] = [];
      const keys: Record<string, unknown> = {};
      for (let i = 0; i < args.length; i++) {
        const a = args[i];
        if (a.kind === "symbol" && a.value.startsWith(":") && a.value !== ":null" && i + 1 < args.length) {
          keys[a.value.slice(1)] = atom(args[++i]);
        } else positional.push(atom(a));
      }
      ops.push(Object.keys(keys).length ? [head, ...positional, keys] : [head, ...positional]);
    } else if (head === "delete-senses") {
      const seq = atom(args[0]);
      const test = args[1];
      if (test.children[0]?.value === "constantly") ops.push(["delete-senses", seq, null, null]);
      else {
        // (lambda (prop) (and (equal (text prop) TEXT) (equal (tag prop) TAG)))
        const strs = JSON.stringify(test).match(/"value":"([^"]+)","children":\[\]/g) ?? [];
        const values = [...JSON.stringify(test).matchAll(/"kind":"string","value":"([^"]*)"/g)].map((m) => m[1]);
        if (values.length !== 2 || !strs.length) throw new Error(`unsupported delete-senses at line ${f.line}`);
        ops.push(["delete-senses", seq, values[1], values[0]]);
      }
    } else if (head === "let" && JSON.stringify(f).includes('"root-p"')) {
      const seq = atom(f.children[1].children[0].children[1].children[2]);
      ops.push(["set-root-p", seq, false]);
    } else if (head === "mapc" && JSON.stringify(f).includes("set-reading")) {
      const seq = atom(f.children[2].children[2].children[2]);
      ops.push(["set-reading-kanji", seq]);
    } else if (head === "ichiran/custom:load-custom-data") {
      ops.push(["load-custom-data", atom(args[0])]);
    } else throw new Error(`unsupported form ${head} at line ${f.line}`);
  }
}
emit(defuns.get("add-errata")!);
const out = `/** GENERATED by scripts/ichiran-build/convert-errata.ts — do not edit.
 * Source: Ichiran dict-errata.lisp (add-errata), commit ${commit},
 * SHA-256 ${createHash("sha256").update(source).digest("hex")}.
 * Copyright (c) 2014 Timofei Shatrov, MIT licence (see licenses/). */
export type ErrataOp = [string, ...unknown[]];
export const ICHIRAN_ERRATA: ErrataOp[] = [
${ops.map((o) => "  " + JSON.stringify(o) + ",").join("\n")}
];
`;
await writeFile("packages/dictionary/src/ichiran-build/errata-data.ts", out);
console.log(`${ops.length} operations`);
